def embed_text(text: str) -> Optional[List[float]]:
    """Encode a single string → 384-d vector. Returns None on failure.

    Phase 54.16 (2026-05-11) — tries the RunPod sidecar first (frees ~1 GB
    EC2 RAM by removing the local sentence-transformers model). Falls back
    to local model if the sidecar is unreachable.
    """
    if not text or not text.strip():
        return None

    # Remote path (preferred — unloads BGE from EC2 RAM)
    try:
        from services.embed_client import embed_remote, is_remote_enabled
        if is_remote_enabled():
            vecs = embed_remote([text])
            if vecs is not None and vecs and vecs[0] is not None:
                return vecs[0]
    except Exception as e:
        logger.debug(f"[TalentGraph] remote embed_text issue: {e}")

    # Local fallback (legacy path — kept until BGE is fully decommissioned)
    model = _get_embed_model()
    if not model:
        return None
    try:
        text = text.strip()[:2000]
        vec = model.encode(text, normalize_embeddings=True, show_progress_bar=False)
        return vec.tolist()
    except Exception as e:
        logger.error(f"[TalentGraph] embed_text local failed: {e}")
        return None


def embed_texts_batch(texts: List[str]) -> List[Optional[List[float]]]:
    """Batch-encode for the backfill script. Much faster than one-by-one.

    Phase 54.16 — sidecar-first. Local fallback only if sidecar disabled
    or fails.
    """
    # Remote path
    try:
        from services.embed_client import embed_remote, is_remote_enabled
        if is_remote_enabled():
            vecs = embed_remote([(t or "")[:2000] for t in texts])
            if vecs is not None:
                return vecs
    except Exception as e:
        logger.debug(f"[TalentGraph] remote embed_texts_batch issue: {e}")

    # Local fallback
    model = _get_embed_model()
    if not model:
        return [None] * len(texts)
    try:
        cleaned = [(t or "").strip()[:2000] for t in texts]
        vecs = model.encode(
            cleaned, normalize_embeddings=True, show_progress_bar=False, batch_size=32
        )
        return [v.tolist() for v in vecs]
    except Exception as e:
        logger.error(f"[TalentGraph] embed_texts_batch local failed: {e}")
        return [None] * len(texts)


def build_candidate_text(candidate: Dict[str, Any]) -> str:
    """Compose the canonical text we want to embed for each candidate.
    Order matters: most-distinctive fields first so they dominate the vector.
    """
    parts = []

    if candidate.get("current_designation"):
        parts.append(f"Role: {candidate['current_designation']}")
    if candidate.get("current_employer") or candidate.get("current_company"):
        parts.append(
            f"Company: {candidate.get('current_employer') or candidate.get('current_company')}"
        )

    skills = candidate.get("key_skills") or candidate.get("skills") or []
    if isinstance(skills, list) and skills:
        parts.append("Skills: " + ", ".join(skills[:30]))

    yrs = candidate.get("experience_years") or candidate.get("total_experience_years")
    if yrs:
        parts.append(f"Experience: {yrs} years")

    if candidate.get("highest_qualification"):
        parts.append(f"Qualification: {candidate['highest_qualification']}")

    loc = candidate.get("current_location") or candidate.get("location")
    if loc:
        parts.append(f"Location: {loc}")

    if candidate.get("current_industry"):
        parts.append(f"Industry: {candidate['current_industry']}")

    # Compact work history (most recent 3 roles)
    work = candidate.get("work_experience") or []
    if isinstance(work, list) and work:
        roles = []
        for w in work[:3]:
            if isinstance(w, dict):
                d = w.get("designation") or w.get("title") or ""
                c = w.get("company") or w.get("employer") or ""
                if d or c:
                    roles.append(f"{d} at {c}".strip())
        if roles:
            parts.append("History: " + " | ".join(roles))

    if candidate.get("profile_summary"):
        parts.append(f"Summary: {candidate['profile_summary'][:500]}")

    return ". ".join(parts).strip()


def build_job_text(job: Dict[str, Any]) -> str:
    """Compose the canonical text for embedding a job. Used by job↔candidate matching."""
    parts = []
    if job.get("title") or job.get("job_title"):
        parts.append(f"Role: {job.get('title') or job.get('job_title')}")
    if job.get("required_skills") or job.get("skills"):
        sk = job.get("required_skills") or job.get("skills") or []
        if isinstance(sk, list):
            parts.append("Skills: " + ", ".join(sk[:30]))
    if job.get("min_experience") or job.get("max_experience"):
        parts.append(
            f"Experience: {job.get('min_experience', 0)}-{job.get('max_experience', '?')} years"
        )
    if job.get("location"):
        parts.append(f"Location: {job['location']}")
    if job.get("description"):
        parts.append(f"Description: {job['description'][:1500]}")
    return ". ".join(parts).strip()


# ──────────────────────────────────────────────────────────────────────────────
# Summary generation (Qwen 14B → free)
# ──────────────────────────────────────────────────────────────────────────────

async def generate_candidate_summary(candidate: Dict[str, Any]) -> Optional[str]:
    """Generate a 3-line TL;DR via Qwen 14B on RunPod. Returns None on failure
    (caller falls back to a simple rule-based summary).
    """
    raw_text = (
        candidate.get("raw_text_for_enrichment")
        or candidate.get("raw_page_text")
        or build_candidate_text(candidate)
    )
    if not raw_text or len(raw_text) < 100:
        return None

    system_prompt = (
        "You are a recruiting analyst. Write a crisp 3-line summary of the "
        "candidate that highlights: (1) their senior-most role and tenure, "
        "(2) their distinctive skill or domain edge, and (3) why a recruiter "
        "should care (e.g. niche stack, leadership, fast progression). "
        "No buzzwords, no fluff. Each line ≤ 25 words. Output the 3 lines only — "
        "no headings, no bullets, no preamble."
    )
    user_prompt = f"Candidate raw profile:\n\n{raw_text[:4000]}\n\nWrite the 3-line summary:"

    try:
        from services.llm_fallback_service import _call_runpod_vllm
        resp = await _call_runpod_vllm(system_prompt, user_prompt, temperature=0.2, text_mode=True)
        if not resp or not resp.get("content"):
            return None
        summary = resp["content"].strip()
        # Strip code-fences if Qwen wrapped it
        if summary.startswith("```"):
            summary = summary.strip("`").strip()
        # Quality gate: reject truncated / non-textual responses (e.g. "[1]", "{}", etc.)
        if len(summary) < 60 or summary.count(" ") < 8:
            logger.warning(f"[TalentGraph] Qwen summary too short/junk: {summary[:80]!r}")
            return None
        # Cap at 600 chars (3 × ~200) so a runaway response can't bloat the DB
        return summary[:600]
    except Exception as e:
        logger.error(f"[TalentGraph] generate_candidate_summary failed: {e}")
        return None


def fallback_rule_summary(candidate: Dict[str, Any]) -> str:
    """Cheap rule-based 3-liner used when Qwen is unavailable."""
    role = candidate.get("current_designation") or "Professional"
    company = (
        candidate.get("current_employer")
        or candidate.get("current_company")
        or "—"
    )
    yrs = (
        candidate.get("experience_years")
        or candidate.get("total_experience_years")
        or "?"
    )
    skills = candidate.get("key_skills") or candidate.get("skills") or []
    top_skills = ", ".join(skills[:5]) if isinstance(skills, list) else str(skills)[:80]
    loc = candidate.get("current_location") or candidate.get("location") or "—"
    notice = candidate.get("notice_period") or "—"

    line1 = f"{role} at {company} with {yrs} years experience."
    line2 = f"Key skills: {top_skills or '—'}." if top_skills else "Skill profile pending."
    line3 = f"Based in {loc}. Notice: {notice}."
    return "\n".join([line1, line2, line3])


