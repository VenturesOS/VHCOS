EMBEDDINGS_COLL = "candidate_embeddings"


async def ensure_embeddings_indexes(db) -> None:
    """Create the indexes we need on `candidate_embeddings`. Safe to call on
    every boot — MongoDB skips already-existing indexes.
    Atlas Vector Search index is created via the Atlas UI; this stub leaves
    a hook for the standard B-tree indexes used by both UI and backfill.
    """
    coll = db[EMBEDDINGS_COLL]
    try:
        await coll.create_index("candidate_id", unique=True)
        await coll.create_index("updated_at")
        await coll.create_index("text_hash")
        logger.info("[TalentGraph] Indexes ensured on candidate_embeddings")
    except Exception as e:
        # Non-fatal — collection may not exist yet on first boot
        logger.warning(f"[TalentGraph] ensure_embeddings_indexes: {e}")


async def upsert_candidate_embedding(
    db,
    candidate: Dict[str, Any],
    *,
    summary: Optional[str] = None,
    force: bool = False,
) -> Dict[str, Any]:
    """Compute & upsert the embedding + summary for a single candidate.

    Args:
        candidate: Raw doc from candidate_bank (must contain `id`)
        summary: If provided, persist as-is. If None, generate via Qwen with
                 fallback to the rule-based summary.
        force: Re-embed even if text_hash matches the stored one

    Returns: {"status": "embedded|skipped|failed", "candidate_id": str}
    """
    cid = candidate.get("id")
    if not cid:
        return {"status": "failed", "reason": "no_candidate_id"}

    text = build_candidate_text(candidate)
    if not text or len(text) < 30:
        return {"status": "skipped", "candidate_id": cid, "reason": "insufficient_text"}

    text_hash = str(hash(text))
    if not force:
        existing = await db[EMBEDDINGS_COLL].find_one(
            {"candidate_id": cid, "text_hash": text_hash}, {"_id": 0, "text_hash": 1}
        )
        if existing:
            return {"status": "skipped", "candidate_id": cid, "reason": "unchanged"}

    # Run the CPU-bound encode off the asyncio loop
    vec = await asyncio.to_thread(embed_text, text)
    if vec is None:
        return {"status": "failed", "candidate_id": cid, "reason": "embedding_failed"}

    # Summary
    if summary is None:
        summary = await generate_candidate_summary(candidate)
        if not summary:
            summary = fallback_rule_summary(candidate)

    now_iso = datetime.now(timezone.utc).isoformat()
    doc = {
        "candidate_id": cid,
        "candidate_name": candidate.get("name"),
        "current_employer": candidate.get("current_employer") or candidate.get("current_company"),
        "current_designation": candidate.get("current_designation"),
        "experience_years": candidate.get("experience_years") or candidate.get("total_experience_years"),
        "current_location": candidate.get("current_location") or candidate.get("location"),
        "embedding": vec,
        "embedding_model": _EMBED_MODEL_NAME,
        "embedding_dim": EMBED_DIM,
        "text_hash": text_hash,
        "source_text": text[:2000],
        "summary": summary,
        "updated_at": now_iso,
    }
    await db[EMBEDDINGS_COLL].update_one(
        {"candidate_id": cid},
        {"$set": doc, "$setOnInsert": {"created_at": now_iso}},
        upsert=True,
    )

    # Mirror the summary back onto candidate_bank so the UI can show it
    # without an extra round-trip.
    await db.candidate_bank.update_one(
        {"id": cid},
        {"$set": {
            "ai_summary": summary,
            "ai_summary_at": now_iso,
            "embedding_indexed_at": now_iso,
        }},
    )
    return {"status": "embedded", "candidate_id": cid, "summary_chars": len(summary or "")}


