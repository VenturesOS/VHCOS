"""
VHC Talent OS — Talent Graph Service (Phase 1+2)

Builds + queries semantic embeddings of candidate profiles for:
  • "Find similar candidates" (candidate-to-candidate similarity)
  • Semantic search ("ML engineer with fintech exp in Bangalore")
  • Job ↔ candidate auto-matching

Design choices:
  • Embeddings stored in dedicated `candidate_embeddings` collection
    (cleaner than bloating candidate_bank with a 384-dim vector per row)
  • Local sentence-transformer model (BGE-small) — free, CPU-only, 80MB
  • MongoDB Atlas Vector Search compatible (drop-in switch in Phase 4-6)
  • Lazy single-instance model load — survives gunicorn worker restarts

The 3-line summary is generated by Qwen 14B on RunPod (free)
and stored alongside the embedding.
"""
from __future__ import annotations
import asyncio
import logging
import os
import time
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional, Tuple

logger = logging.getLogger(__name__)

# ── Embedding model (lazy-loaded, single instance per process) ────────────────
# BGE-small-en-v1.5 — 384-dim, ~80 MB on disk, ~50 ms per encode on CPU
_EMBED_MODEL = None
_EMBED_MODEL_NAME = os.environ.get(
    "EMBEDDING_MODEL", "BAAI/bge-small-en-v1.5"
)
EMBED_DIM = 384


def _get_embed_model():
    """Lazy-load and cache the sentence-transformer model.
    First call takes ~3s (download + load); subsequent calls reuse it.
    """
    global _EMBED_MODEL
    if _EMBED_MODEL is not None:
        return _EMBED_MODEL
    try:
        from sentence_transformers import SentenceTransformer
        logger.info(f"[TalentGraph] Loading embedding model: {_EMBED_MODEL_NAME}")
        t0 = time.time()
        _EMBED_MODEL = SentenceTransformer(_EMBED_MODEL_NAME, device="cpu")
        logger.info(f"[TalentGraph] Model ready in {time.time() - t0:.1f}s")
        return _EMBED_MODEL
    except Exception as e:
        logger.error(f"[TalentGraph] Failed to load model: {e}")
        _EMBED_MODEL = False  # sentinel so we don't retry every call
        return None


