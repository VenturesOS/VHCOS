async def find_similar_candidates(
    db,
    candidate_id: str,
    limit: int = 10,
    min_score: float = 0.55,
) -> List[Dict[str, Any]]:
    """Return up to `limit` other candidates whose vectors are most similar.
    Uses cosine similarity (vectors are L2-normalized so dot-product == cosine).

    Strategy:
      • Fast path: MongoDB Atlas $vectorSearch (if index `candidate_vector_idx` exists)
      • Slow path: pull all vectors + numpy cosine in-process
    """
    seed = await db[EMBEDDINGS_COLL].find_one({"candidate_id": candidate_id}, {"_id": 0})
    if not seed or not seed.get("embedding"):
        return []
    seed_vec = seed["embedding"]

    # Try Atlas Vector Search first
    try:
        pipeline = [
            {
                "$vectorSearch": {
                    "index": "candidate_vector_idx",
                    "path": "embedding",
                    "queryVector": seed_vec,
                    "numCandidates": max(limit * 10, 100),
                    "limit": limit + 1,  # +1 because we'll filter out the seed itself
                }
            },
            {
                "$project": {
                    "_id": 0,
                    "candidate_id": 1,
                    "candidate_name": 1,
                    "current_employer": 1,
                    "current_designation": 1,
                    "experience_years": 1,
                    "current_location": 1,
                    "summary": 1,
                    "score": {"$meta": "vectorSearchScore"},
                }
            },
        ]
        results = await db[EMBEDDINGS_COLL].aggregate(pipeline).to_list(limit + 1)
        if results:
            return [
                r for r in results
                if r.get("candidate_id") != candidate_id and r.get("score", 0) >= min_score
            ][:limit]
    except Exception as e:
        logger.info(f"[TalentGraph] $vectorSearch unavailable, falling back: {e}")

    # Fallback: in-memory cosine
    return await _cosine_topk_fallback(db, seed_vec, exclude_id=candidate_id, limit=limit, min_score=min_score)


async def find_candidates_by_text(
    db,
    query: str,
    limit: int = 20,
    min_score: float = 0.40,
    routing_key: Optional[str] = None,
    timing: Optional[Dict[str, int]] = None,
    location_hint: Optional[str] = None,
) -> List[Dict[str, Any]]:
    """Free-form semantic search ('ML engineer with fintech in Bangalore').

    Optional ``timing`` dict — when passed, populated with per-step
    millisecond timings (`embed_ms`, `vector_search_ms`, `cosine_fallback_ms`,
    `rerank_ms`, `enrich_ms`). Lets the talent-search endpoint surface a
    latency breakdown to callers without a redeploy.

    Uses a hybrid score = 0.85·cosine + 0.15·keyword_overlap so that candidates
    whose source text actually mentions the query's discriminative keywords
    (location, industry, role tokens) rank above those that only match
    semantically. The displayed `score` remains pure cosine so scores stay
    comparable across queries.

    A/B (Phase 56.8, Jun 2026): when `routing_key` lands in the LTR
    bucket (env `LTR_AB_PCT`, default 10%), the rerank step uses the
    offline-trained XGBoost ranker. All other traffic continues on the
    cross-encoder (or hybrid fallback) path. Caller can inspect
    `results[0]["match_type"]` to know which arm ran ("ltr_xgboost",
    "cross_encoder", or "vector"/"hybrid" depending on fallback).

    FIX (Phase 55, 2026-02): only ~1.4% of `candidate_bank` has embeddings
    indexed, so a pure vector search misses ~98% of the talent pool. When the
    embedding pool returns fewer hits than requested, top up with a keyword +
    smart-tag fallback over the live `candidate_bank` so users never see an
    empty page just because the backfill hasn't caught up.
    """
    _t = time.time()
    qvec = await asyncio.to_thread(embed_text, query)
    if timing is not None: timing["embed_ms"] = int((time.time() - _t) * 1000)
    if not qvec:
        return await _keyword_fallback_search(db, query, limit)

    # Pull a wider pool than the user asked for so re-rank has room to work.
    fetch_limit = max(limit * 3, 60)

    _t = time.time()
    pool = None
    try:
        pipeline = [
            {
                "$vectorSearch": {
                    "index": "candidate_vector_idx",
                    "path": "embedding",
                    "queryVector": qvec,
                    "numCandidates": max(fetch_limit * 10, 200),
                    "limit": fetch_limit,
                }
            },
            {
                "$project": {
                    "_id": 0,
                    "candidate_id": 1,
                    "candidate_name": 1,
                    "current_employer": 1,
                    "current_designation": 1,
                    "experience_years": 1,
                    "current_location": 1,
                    "summary": 1,
                    "source_text": 1,
                    "score": {"$meta": "vectorSearchScore"},
                }
            },
        ]
        results = await db[EMBEDDINGS_COLL].aggregate(pipeline).to_list(fetch_limit)
        if results:
            pool = [r for r in results if r.get("score", 0) >= min_score]
    except Exception as e:
        logger.info(f"[TalentGraph] text-search via $vectorSearch unavailable: {e}")
    if timing is not None:
        timing["vector_search_ms"] = int((time.time() - _t) * 1000)
        timing["vector_search_hits"] = len(pool) if pool is not None else 0

    if pool is None:
        _t = time.time()
        pool = await _cosine_topk_fallback(
            db, qvec, exclude_id=None, limit=fetch_limit, min_score=min_score, with_text=True
        )
        if timing is not None:
            timing["cosine_fallback_ms"] = int((time.time() - _t) * 1000)
            timing["cosine_fallback_hits"] = len(pool)

    # ── Location seed (mandate-driven recall fix, Phase 55 / 2026-06-16) ──
    # The vector index covers only ~1.4% of `candidate_bank`. For a tight
    # mandate (e.g. Bangalore + 19-25L), the cluster-routed semantic pool
    # routinely returns 0 location-correct candidates — and the keyword
    # top-up at the bottom never fires because `len(pool) >= limit` from
    # other geographies. Seed the pool with a location-scoped DB scan so
    # the reranker (and the downstream strict filter) actually have
    # Bangalore candidates to work with.
    if location_hint and (location_hint or "").strip():
        _t = time.time()
        loc = location_hint.strip()
        # Indian city aliases (Bangalore↔Bengaluru, Bombay↔Mumbai, …).
        # Kept inline so this service stays standalone — same map exists in
        # routes/talent_search.py for the strict-filter intersection.
        _CITY_ALIASES = {
            "bangalore": ["bengaluru"], "bengaluru": ["bangalore"],
            "bombay": ["mumbai"],       "mumbai": ["bombay"],
            "calcutta": ["kolkata"],    "kolkata": ["calcutta"],
            "madras": ["chennai"],      "chennai": ["madras"],
            "gurgaon": ["gurugram"],    "gurugram": ["gurgaon"],
        }
        base = loc.lower()
        loc_terms = [base] + _CITY_ALIASES.get(base, [])
        seen_ids = {r.get("candidate_id") for r in (pool or []) if r.get("candidate_id")}
        # Token-scoped query so the seeder doesn't pull every Bangalore
        # candidate — only those that also share at least one query token.
        # Inject ALL location aliases so Bengaluru-stored candidates surface
        # for a Bangalore mandate (and vice-versa).
        seed_query = f"{' '.join(loc_terms)} {query}".strip()
        seed = await _keyword_fallback_search(
            db, seed_query, max(limit * 2, 40), exclude_ids=seen_ids
        )
        # Keep only seeds whose location actually matches the hint (or alias).
        # `_keyword_fallback_search` joins location with skills/employer/etc.
        # via $or, so a seed can come in from skill-match alone.
        seed = [
            s for s in seed
            if any(t in (str(s.get("current_location") or "")).lower() for t in loc_terms)
        ]
        # Track seed IDs so we can guarantee they're in the final result
        # set even if the reranker scores them low (no embedding/LTR features).
        location_seed_ids: set = set()
        if seed:
            for s in seed:
                s.setdefault("match_type", "location_seed")
                if s.get("candidate_id"):
                    location_seed_ids.add(s["candidate_id"])
            pool = (pool or []) + seed
        if timing is not None:
            timing["location_seed_ms"] = int((time.time() - _t) * 1000)
            timing["location_seed_hits"] = len(seed)
    else:
        location_seed_ids = set()

    # ── A/B rerank ──────────────────────────────────────────────────
    from services import ltr_service
    arm_ltr = ltr_service.should_use_ltr_arm(routing_key or query)

    _t = time.time()
    ranked = None
    if arm_ltr and pool:
        await _load_ltr_features(db, pool)
        ranked = ltr_service.rerank(pool, query, limit)
        if timing is not None: timing["rerank_arm"] = "ltr_xgboost"
    if ranked is None:
        # Default arm: cross-encoder (precision-boost) → hybrid fallback.
        ranked = (await asyncio.to_thread(_cross_encoder_rerank, pool, query, limit)) if pool else None
        if ranked is None:
            ranked = _hybrid_rerank(pool, query, limit)
            if timing is not None: timing["rerank_arm"] = "hybrid"
        else:
            if timing is not None: timing["rerank_arm"] = "cross_encoder"
    if timing is not None: timing["rerank_ms"] = int((time.time() - _t) * 1000)

    # Guarantee location seeds survive the rerank cull. A `_keyword_fallback_search`
    # candidate has no embedding (cosine=0) and no LTR features, so both arms
    # tend to push them to the bottom — even when the recruiter explicitly
    # filtered on that location. Re-inject any missing seeds so the strict
    # filter downstream has a chance to keep them.
    if location_seed_ids:
        ranked_ids = {r.get("candidate_id") for r in ranked if r.get("candidate_id")}
        missing = [s for s in (pool or []) if s.get("candidate_id") in (location_seed_ids - ranked_ids)]
        if missing:
            # Slot seeds at the END so they don't crowd out high-confidence
            # semantic hits — the strict filter (called by the route layer)
            # will reorder by relevance.
            ranked = ranked + missing
            if timing is not None:
                timing["location_seed_reinjected"] = len(missing)

    _t = time.time()
    await _enrich_with_candidate_bank(db, ranked)
    if timing is not None: timing["enrich_ms"] = int((time.time() - _t) * 1000)

    for r in ranked:
        r.setdefault("match_type", "vector")

    # Top-up with keyword fallback so users always see a usable list even
    # when embedding coverage is sparse.
    if len(ranked) < limit:
        _t = time.time()
        seen_ids = {r.get("candidate_id") for r in ranked if r.get("candidate_id")}
        needed   = limit - len(ranked)
        fallback = await _keyword_fallback_search(db, query, needed, exclude_ids=seen_ids)
        ranked.extend(fallback)
        if timing is not None: timing["keyword_topup_ms"] = int((time.time() - _t) * 1000)

    return ranked


async def _keyword_fallback_search(
    db,
    query: str,
    limit: int,
    exclude_ids: Optional[set] = None,
) -> List[Dict[str, Any]]:
    """Keyword + smart-tag fallback over `candidate_bank` when the embedding
    pool is sparse. Returns docs in the same shape as the vector search path
    so downstream code doesn't branch.
    """
    import re as _re_kw
    tokens = [t.strip() for t in _re_kw.findall(r"[A-Za-z0-9\.\+\#]{2,}", query) if t.strip()]
    # Drop very common stopwords so "with", "in", "the" don't dominate
    STOP = {"with", "and", "the", "for", "from", "in", "of", "to", "a", "an",
            "or", "at", "on", "by", "is", "be", "as", "into", "experience",
            "experienced", "senior", "junior", "lead"}
    tokens = [t for t in tokens if t.lower() not in STOP][:8]
    if not tokens:
        return []

    pat = "|".join(_re_kw.escape(t) for t in tokens)
    base_or = [
        {"smart_tags":  {"$regex": pat, "$options": "i"}},
        {"skills":      {"$regex": pat, "$options": "i"}},
        {"designation": {"$regex": pat, "$options": "i"}},
        {"headline":    {"$regex": pat, "$options": "i"}},
        {"current_employer": {"$regex": pat, "$options": "i"}},
        {"location":    {"$regex": pat, "$options": "i"}},
        {"industry":    {"$regex": pat, "$options": "i"}},
        {"summary":     {"$regex": pat, "$options": "i"}},
    ]
    q = {"$or": base_or}
    if exclude_ids:
        q = {"$and": [q, {"id": {"$nin": list(exclude_ids)}}]}

    docs = await db.candidate_bank.find(
        q,
        {
            "_id": 0, "id": 1, "name": 1,
            "designation": 1, "current_designation": 1, "headline": 1,
            "current_employer": 1, "current_company": 1,
            "location": 1, "current_location": 1,
            "experience_years": 1, "total_experience_years": 1,
            "skills": 1, "smart_tags": 1, "summary": 1,
        },
    ).sort("created_at", -1).limit(limit).to_list(limit)

    # Score = how many query tokens overlap with the document text
    out = []
    q_tokens_lower = {t.lower() for t in tokens}
    for d in docs:
        text = " ".join([
            str(d.get("designation") or d.get("current_designation") or ""),
            str(d.get("headline") or ""),
            str(d.get("current_employer") or d.get("current_company") or ""),
            str(d.get("location") or d.get("current_location") or ""),
            " ".join(d.get("skills") or []),
            " ".join(d.get("smart_tags") or []),
            str(d.get("summary") or "")[:500],
        ]).lower()
        hits = sum(1 for t in q_tokens_lower if t in text)
        score = hits / max(len(q_tokens_lower), 1)
        out.append({
            "candidate_id":  d.get("id"),
            "candidate_name": d.get("name"),
            "current_employer": d.get("current_employer") or d.get("current_company"),
            "current_designation": d.get("designation") or d.get("current_designation") or d.get("headline"),
            "current_location": d.get("location") or d.get("current_location"),
            "experience_years": d.get("experience_years") or d.get("total_experience_years"),
            "summary": d.get("summary"),
            "score": round(0.35 + 0.5 * score, 4),   # 0.35..0.85, clearly < pure vector hits
            "match_type": "keyword",
        })
    out.sort(key=lambda x: x["score"], reverse=True)
    return out


async def _enrich_with_candidate_bank(db, results: List[Dict[str, Any]]) -> None:
    """Fill in any null name/designation/employer/location fields from the live
    `candidate_bank` collection. The embedding snapshot was taken at indexing
    time, so it can be stale (e.g. early Naukri captures had null designations).
    Mutates `results` in-place.
    """
    if not results:
        return
    # Enrich any result missing ANY of the display/filter fields. The old
    # logic required ALL THREE to be missing — but Naukri embeddings often
    # carry the designation while `current_location` is empty (the field
    # name in candidate_bank is `location`, not `current_location`), so a
    # strict location filter would cull them before this hydration ran.
    needs = [
        r for r in results
        if not r.get("current_designation")
        or not r.get("current_employer")
        or not r.get("current_location")
        or r.get("experience_years") is None
    ]
    if not needs:
        return
    ids = [r["candidate_id"] for r in needs if r.get("candidate_id")]
    if not ids:
        return
    cursor = db.candidate_bank.find(
        {"id": {"$in": ids}},
        {
            "_id": 0, "id": 1, "name": 1,
            "current_designation": 1, "current_employer": 1, "current_company": 1,
            "current_location": 1, "location": 1,
            "total_experience_years": 1, "experience_years": 1,
            "headline": 1, "resume_headline": 1,
            "work_experience": 1,
        },
    )
    by_id = {d["id"]: d async for d in cursor}
    for r in results:
        c = by_id.get(r.get("candidate_id"))
        if not c:
            continue
        # Designation: live → most-recent work entry → headline (first 80 chars)
        designation = r.get("current_designation") or c.get("current_designation")
        if not designation:
            for w in (c.get("work_experience") or []):
                if isinstance(w, dict):
                    designation = w.get("designation") or w.get("title")
                    if designation:
                        break
        if not designation:
            headline = (c.get("resume_headline") or c.get("headline") or "").strip()
            if headline:
                designation = (headline[:80] + "…") if len(headline) > 80 else headline

        r["candidate_name"] = r.get("candidate_name") or c.get("name")
        r["current_designation"] = designation
        r["current_employer"] = (
            r.get("current_employer")
            or c.get("current_employer")
            or c.get("current_company")
        )
        r["current_location"] = (
            r.get("current_location") or c.get("current_location") or c.get("location")
        )
        r["experience_years"] = (
            r.get("experience_years")
            or c.get("experience_years")
            or c.get("total_experience_years")
        )


async def _load_ltr_features(db, results: List[Dict[str, Any]]) -> None:
    """Fetch the candidate fields the LTR ranker needs (skills, cluster_id,
    updated_at) onto each result in-place. Runs only on the A/B-selected
    arm so we don't pay this DB cost for cross-encoder / hybrid traffic.

    Only fetches for results that don't already carry the LTR fields,
    making this safe to call after a previous rerank.
    """
    if not results:
        return
    need_ids = [
        r["candidate_id"] for r in results
        if r.get("candidate_id") and "skills" not in r
    ]
    if not need_ids:
        return
    cursor = db.candidate_bank.find(
        {"id": {"$in": need_ids}},
        {"_id": 0, "id": 1, "skills": 1, "cluster_id": 1, "updated_at": 1, "created_at": 1},
    )
    by_id = {d["id"]: d async for d in cursor}
    for r in results:
        c = by_id.get(r.get("candidate_id"))
        if not c:
            continue
        r["skills"] = c.get("skills")
        r["cluster_id"] = c.get("cluster_id")
        r["updated_at"] = c.get("updated_at") or c.get("created_at")


# ──────────────────────────────────────────────────────────────────────────────
# Hybrid re-rank: cosine + lightweight keyword overlap
# ──────────────────────────────────────────────────────────────────────────────

# Words too common to discriminate one candidate from another
_STOPWORDS = frozenset({
    "and", "the", "for", "with", "who", "has", "have", "are", "any", "all",
    "looking", "candidate", "candidates", "experience", "experienced", "year",
    "years", "exp", "open", "work", "working", "role", "based", "from", "this",
    "that", "preferably", "preferred", "must", "should", "good", "great", "strong",
})

def _query_keywords(query: str) -> List[str]:
    import re
    tokens = re.findall(r"[a-zA-Z][a-zA-Z+\-\.]{2,}", (query or "").lower())
    out = []
    seen = set()
    for t in tokens:
        if t in _STOPWORDS or t in seen:
            continue
        seen.add(t)
        out.append(t)
    return out


def _cross_encoder_rerank(
    results: List[Dict[str, Any]],
    query: str,
    limit: int,
) -> Optional[List[Dict[str, Any]]]:
    """Optional precision pass using the BGE cross-encoder on the RunPod sidecar.

    Activated when env `CROSS_ENCODER_ENABLED=true` (default off, behind a
    feature flag). Only runs when there are ≥4 candidates and the sidecar
    is reachable. Falls back to None on any failure so the caller can use
    the cheaper bi-encoder rerank.

    The cross-encoder is a one-time ~5× precision boost on the *top of the
    cosine pool* — we limit the input batch to MAX_PAIRS to keep the
    request bounded (≤200ms even on cold GPU).
    """
    MAX_PAIRS = 64  # sidecar hard cap is 128; keep room for safety
    if os.environ.get("CROSS_ENCODER_ENABLED", "false").lower() not in ("1", "true", "yes"):
        return None
    if not results or len(results) < 4:
        return None
    try:
        from services.embed_client import rerank_remote, is_remote_enabled
        if not is_remote_enabled():
            return None
        # Build a compact doc string per candidate — same fields as
        # _hybrid_rerank haystack but joined with spaces.
        pool = results[:MAX_PAIRS]
        docs = []
        for r in pool:
            doc = " | ".join(filter(None, [
                (r.get("candidate_name") or "")[:80],
                (r.get("current_designation") or "")[:80],
                (r.get("current_employer") or "")[:80],
                (r.get("current_location") or "")[:60],
                (r.get("summary") or r.get("source_text") or "")[:600],
            ]))
            docs.append(doc.strip() or (r.get("candidate_name") or "n/a"))

        hits = rerank_remote(query=query[:400], documents=docs, top_k=limit)
        if not hits:
            return None
        # Re-order pool by sidecar score; expose score in result for the UI.
        idx_map = {h["index"]: float(h["score"]) for h in hits}
        for i, r in enumerate(pool):
            r["_rerank_score"] = idx_map.get(i, 0.0)
            r["match_type"] = "cross_encoder"
        pool.sort(key=lambda r: r.get("_rerank_score") or 0.0, reverse=True)
        for r in pool:
            r.pop("source_text", None)
        return pool[:limit]
    except Exception as e:  # noqa: BLE001
        logger.warning(f"[TalentGraph] cross-encoder rerank failed: {e!s} — falling back")
        return None


def _hybrid_rerank(
    results: List[Dict[str, Any]], query: str, limit: int
) -> List[Dict[str, Any]]:
    """Re-rank by 0.85·cosine + 0.15·keyword_overlap. Returns top-`limit`.

    Each result must already have `score` (cosine, 0-1) and ideally
    `source_text` for keyword matching. Falls back to designation/employer/
    location/summary when source_text is absent.
    """
    if not results:
        return []
    keywords = _query_keywords(query)
    if not keywords:
        # No discriminative tokens — keep pure cosine ranking
        results.sort(key=lambda r: r.get("score") or 0.0, reverse=True)
        return results[:limit]

    for r in results:
        haystack = " ".join([
            (r.get("source_text") or ""),
            (r.get("candidate_name") or ""),
            (r.get("current_designation") or ""),
            (r.get("current_employer") or ""),
            (r.get("current_location") or ""),
            (r.get("summary") or ""),
        ]).lower()
        if not haystack:
            r["_keyword_overlap"] = 0.0
            r["_combined_score"] = r.get("score") or 0.0
            continue
        hits = sum(1 for kw in keywords if kw in haystack)
        overlap = hits / max(len(keywords), 1)  # 0..1
        r["_keyword_overlap"] = round(overlap, 3)
        r["_combined_score"] = 0.85 * (r.get("score") or 0.0) + 0.15 * overlap

    results.sort(key=lambda r: r.get("_combined_score") or 0.0, reverse=True)
    # Drop the internal helper fields before returning to the API
    for r in results:
        r.pop("_combined_score", None)
        # keep _keyword_overlap visible — useful for the UI / future debugging
        r.pop("source_text", None)
    return results[:limit]


